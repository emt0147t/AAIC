                "print(f\"Measured Throughput:        {measured_samples_per_sec:.2f} samples / second\")\n",
                "print(f\"Peak VRAM Allocated:        {peak_alloc_mb:.2f} MB\")\n",
                "print(f\"Peak VRAM Reserved:         {peak_res_mb:.2f} MB\")\n",
                "print(f\"Remaining VRAM Headroom:    {headroom_mb:.2f} MB\")\n",
                "print(f\"Total Full E1 Steps:        {FULL_E1_OPTIMIZER_STEPS} optimizer steps\")\n",
                "print(f\"ESTIMATED FULL E1 DURATION: {estimated_e1_duration_hours:.2f} hours ({estimated_e1_duration_sec:.1f} s)\")\n",
                "print(\"=\" * 70)\n",
