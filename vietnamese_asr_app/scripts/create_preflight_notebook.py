                "import time\n",
                "import numpy as np\n",
                "from torch.utils.data import Dataset, DataLoader\n",
                "from transformers import get_cosine_schedule_with_warmup\n",
                "import json\n",
                "\n",
                "MICRO_BATCH = 4\n",
                "GRAD_ACCUM = 8\n",
                "EFFECTIVE_BATCH = MICRO_BATCH * GRAD_ACCUM  # 32\n",
                "WARMUP_OPT_STEPS = 5\n",
                "MEASURED_OPT_STEPS = 50\n",
                "TOTAL_BENCH_STEPS = WARMUP_OPT_STEPS + MEASURED_OPT_STEPS\n",
                "LEARNING_RATE = 1e-4\n",
                "WEIGHT_DECAY = 0.01\n",
                "\n",
                "class SyntheticAudioDataset(Dataset):\n",
                "    def __init__(self, size=2500, sample_rate=16000, duration=4.0):\n",
                "        self.size = size\n",
                "        self.audio_len = int(sample_rate * duration)\n",
                "    def __len__(self):\n",
                "        return self.size\n",
                "    def __getitem__(self, idx):\n",
                "        waveform = np.sin(2 * np.pi * 440 * np.linspace(0, 4.0, self.audio_len)).astype(np.float32)\n",
                "        text = \"thực nghiệm kiểm tra hiệu năng hệ thống nhận dạng tiếng việt trên hạ tầng tính toán\"\n",
                "        inputs = processor.feature_extractor(waveform, sampling_rate=16000, return_tensors=\"pt\")\n",
                "        labels = processor.tokenizer(text, return_tensors=\"pt\").input_ids[0]\n",
                "        return {\"input_features\": inputs.input_features[0], \"labels\": labels}\n",
                "\n",
                "def collate_fn(batch):\n",
                "    input_features = torch.stack([item[\"input_features\"] for item in batch])\n",
                "    labels = [item[\"labels\"] for item in batch]\n",
                "    max_len = max(len(l) for l in labels)\n",
                "    padded_labels = torch.full((len(labels), max_len), -100, dtype=torch.long)\n",
                "    for i, l in enumerate(labels):\n",
                "        padded_labels[i, :len(l)] = l\n",
                "    return {\"input_features\": input_features, \"labels\": padded_labels}\n",
                "\n",
                "dataset = SyntheticAudioDataset(size=TOTAL_BENCH_STEPS * EFFECTIVE_BATCH + 128)\n",
                "dataloader = DataLoader(dataset, batch_size=MICRO_BATCH, shuffle=False, collate_fn=collate_fn)\n",
                "\n",
                "optimizer = torch.optim.AdamW(filter(lambda p: p.requires_grad, model.parameters()), lr=LEARNING_RATE, weight_decay=WEIGHT_DECAY)\n",
                "total_micro_steps = TOTAL_BENCH_STEPS * GRAD_ACCUM\n",
                "scheduler = get_cosine_schedule_with_warmup(optimizer, num_warmup_steps=int(total_micro_steps * 0.1), num_training_steps=total_micro_steps)\n",
                "scaler = torch.amp.GradScaler('cuda', enabled=torch.cuda.is_available())\n",
                "\n",
                "model.train()\n",
                "micro_step_count = 0\n",
                "opt_step_count = 0\n",
                "\n",
                "# --- PHASE 1: WARMUP STEPS (EXCLUDED FROM TIMING) ---\n",
                "print(f\"[1/2] Running {WARMUP_OPT_STEPS} warmup optimizer steps (excluded from timing)...\")\n",
                "data_iter = iter(dataloader)\n",
                "while opt_step_count < WARMUP_OPT_STEPS:\n",
                "    batch = next(data_iter)\n",
                "    feat = batch[\"input_features\"].to(device)\n",
                "    lab = batch[\"labels\"].to(device)\n",
                "    with torch.amp.autocast('cuda', enabled=torch.cuda.is_available()):\n",
                "        out = model(input_features=feat, labels=lab)\n",
                "        loss = out.loss / GRAD_ACCUM\n",
                "    scaler.scale(loss).backward()\n",
                "    micro_step_count += 1\n",
                "    if micro_step_count % GRAD_ACCUM == 0:\n",
                "        scaler.unscale_(optimizer)\n",
                "        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)\n",
                "        scaler.step(optimizer)\n",
                "        scaler.update()\n",
                "        optimizer.zero_grad()\n",
                "        scheduler.step()\n",
                "        opt_step_count += 1\n",
                "\n",
                "# --- PHASE 2: SYNCHRONIZATION & PEAK MEMORY RESET ---\n",
                "if torch.cuda.is_available():\n",
                "    torch.cuda.synchronize()\n",
                "    torch.cuda.reset_peak_memory_stats()\n",
                "    torch.cuda.empty_cache()\n",
                "\n",
                "# --- PHASE 3: MEASURED BENCHMARK (50 OPTIMIZER STEPS) ---\n",
                "print(f\"[2/2] Measuring {MEASURED_OPT_STEPS} optimizer steps with CUDA synchronization...\")\n",
                "measured_step_times = []\n",
                "measured_losses = []\n",
                "current_loss = 0.0\n",
                "measured_opt_count = 0\n",
                "\n",
                "if torch.cuda.is_available():\n",
                "    torch.cuda.synchronize()\n",
                "start_measured_total = time.time()\n",
                "step_start = time.time()\n",
                "\n",
                "while measured_opt_count < MEASURED_OPT_STEPS:\n",
                "    batch = next(data_iter)\n",
                "    feat = batch[\"input_features\"].to(device)\n",
                "    lab = batch[\"labels\"].to(device)\n",
                "    with torch.amp.autocast('cuda', enabled=torch.cuda.is_available()):\n",
                "        out = model(input_features=feat, labels=lab)\n",
                "        loss = out.loss / GRAD_ACCUM\n",
                "    scaler.scale(loss).backward()\n",
                "    current_loss += loss.item() * GRAD_ACCUM\n",
                "    micro_step_count += 1\n",
                "    if micro_step_count % GRAD_ACCUM == 0:\n",
                "        scaler.unscale_(optimizer)\n",
                "        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)\n",
                "        scaler.step(optimizer)\n",
                "        scaler.update()\n",
                "        optimizer.zero_grad()\n",
                "        scheduler.step()\n",
                "        if torch.cuda.is_available():\n",
                "            torch.cuda.synchronize()\n",
                "        step_dur = time.time() - step_start\n",
                "        measured_step_times.append(step_dur)\n",
                "        measured_losses.append(current_loss)\n",
                "        measured_opt_count += 1\n",
                "        if measured_opt_count % 10 == 0 or measured_opt_count == 1:\n",
                "            print(f\"Measured Step [{measured_opt_count:2d}/{MEASURED_OPT_STEPS}] | Loss: {current_loss:.4f} | Latency: {step_dur:.3f}s\")\n",
                "        current_loss = 0.0\n",
                "        step_start = time.time()\n",
                "\n",
                "if torch.cuda.is_available():\n",
                "    torch.cuda.synchronize()\n",
                "total_measured_time = time.time() - start_measured_total\n",
                "total_measured_samples = measured_opt_count * EFFECTIVE_BATCH\n",
                "measured_samples_per_sec = total_measured_samples / total_measured_time\n",
                "mean_step_time = np.mean(measured_step_times)\n",
                "min_step_time = np.min(measured_step_times)\n",
                "max_step_time = np.max(measured_step_times)\n",
                "step_range = max_step_time - min_step_time\n",
                "\n",
                "# --- MEMORY MEASUREMENTS ---\n",
                "if torch.cuda.is_available():\n",
                "    peak_alloc_mb = torch.cuda.max_memory_allocated() / (1024 * 1024)\n",
                "    peak_res_mb = torch.cuda.max_memory_reserved() / (1024 * 1024)\n",
                "    total_vram_mb = torch.cuda.get_device_properties(0).total_memory / (1024 * 1024)\n",
                "    headroom_mb = total_vram_mb - peak_res_mb\n",
                "else:\n",
                "    peak_alloc_mb = 0.0\n",
                "    peak_res_mb = 0.0\n",
                "    total_vram_mb = 0.0\n",
